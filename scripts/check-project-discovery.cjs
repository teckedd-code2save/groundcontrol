// Only run inside an unclaimed, disposable desktop acceptance instance.
const assert = require('node:assert/strict');
const { randomBytes } = require('node:crypto');
const fs = require('node:fs');
async function main() {
  assert.equal(process.env.GC_DESKTOP_MODE, '1');
  const root = process.env.GC_TEST_SOURCE_ROOT;
  assert.ok(root && root.includes('project-discovery-acceptance-'));
  const testPassword = randomBytes(24).toString('base64url') + String.fromCharCode(65, 97, 49, 33);
  const base = 'http://127.0.0.1:3000';
  const identity = `compose:${process.env.GC_TEST_COMPOSE_PROJECT}`;
  let cookie = '';
  async function call(url, payload, method) {
    const response = await fetch(base + url, { method: method || (payload === undefined ? 'GET' : 'POST'), headers: { 'Content-Type': 'application/json', Cookie: cookie }, body: payload === undefined ? undefined : JSON.stringify(payload), signal: AbortSignal.timeout(90000) });
    return { status: response.status, headers: response.headers, data: await response.json() };
  }
  if (process.env.GC_TEST_RESUME === '1') {
    cookie = fs.readFileSync('/tmp/gc-discovery-test-session', 'utf8');
    const inventory = await call('/api/deployment-inventory');
    assert.equal(inventory.status, 200); assert.ok(!inventory.data.candidates.some((item) => item.id === identity));
    await call('/api/deployment-inventory', { action: 'restore', candidateId: identity });
    assert.ok((await call('/api/deployment-inventory')).data.candidates.some((item) => item.id === identity));
    const projects = (await call('/api/project-groups')).data.projects;
    assert.ok(projects.some((p) => p.sources.length === 1 && p.deployments.some((d) => d.environmentName === 'Local')));
    console.log(JSON.stringify({ restartPersistence: 'passed', restoreAfterRestart: 'passed', projectPersistence: 'passed' })); return;
  }
  assert.equal((await call('/api/auth/claim')).data.claimed, false, 'Never run on an owned installation');
  assert.equal((await call('/api/deployment-inventory')).status, 401);
  assert.equal((await call('/api/project-import/github?url=https%3A%2F%2Fgithub.com%2Foctocat%2FHello-World')).status, 401);
  assert.ok(process.env.GC_TEST_CLAIM_TOKEN);
  const claim = await call('/api/auth/claim', { token: process.env.GC_TEST_CLAIM_TOKEN, username: 'discovery-acceptance', password: testPassword });
  assert.equal(claim.status, 200); cookie = claim.headers.get('set-cookie').split(';')[0]; fs.writeFileSync('/tmp/gc-discovery-test-session', cookie, { mode: 0o600 });
  const home = await call('/api/deployment-inventory', { action: 'browse_folders' });
  assert.equal(home.status, 200); assert.equal(home.data.path, process.env.GC_HOST_HOME); assert.equal(home.data.error, undefined);
  assert.ok(home.data.folders.some((item) => item.name === 'Documents'));
  const fixtureFolders = await call('/api/deployment-inventory', { action: 'browse_folders', sourcePath: root });
  assert.equal(fixtureFolders.data.error, undefined); assert.ok(fixtureFolders.data.folders.some((item) => item.name === 'web app'));
  const child = await call('/api/deployment-inventory', { action: 'browse_folders', sourcePath: root + '/web app' });
  assert.equal(child.data.parentPath, root); assert.equal(child.data.canSelect, true);
  assert.equal((await call('/api/deployment-inventory', { action: 'browse_folders', sourcePath: '/etc' })).status, 400);
  const scan = await call('/api/deployment-inventory', { action: 'inspect_folder', sourcePath: root });
  assert.equal(scan.status, 200, JSON.stringify(scan.data));
  assert.deepEqual(scan.data.projects.map((item) => item.name).sort(), ['api', 'compose-app', 'dotnet', 'web app']);
  assert.ok(scan.data.projects.find((item) => item.name === 'web app').technologies.includes('JavaScript / TypeScript'));
  assert.ok(scan.data.projects.find((item) => item.name === 'dotnet').technologies.includes('.NET'));
  assert.equal((await call('/api/deployment-inventory', { action: 'inspect_folder', sourcePath: root + '/missing' })).status, 404);
  const noAccount = await call('/api/github/repositories');
  assert.equal(noAccount.status, 200); assert.equal(noAccount.data.needsOwner, true);
  assert.equal((await call('/api/project-import/github', { repositoryUrl: 'http://127.0.0.1/private' })).status, 400);
  const githubUrl = 'https://github.com/octocat/Hello-World';
  const githubPreview = await call('/api/project-import/github?url=' + encodeURIComponent(githubUrl));
  assert.equal(githubPreview.status, 200, JSON.stringify(githubPreview.data));
  assert.equal(githubPreview.data.repository.fullName, 'octocat/Hello-World');
  const githubImport = await call('/api/project-import/github', { repositoryUrl: githubUrl, name: 'Public GitHub acceptance', description: 'Disposable import test' });
  assert.equal(githubImport.status, 201, JSON.stringify(githubImport.data));
  assert.equal(githubImport.data.project.repositoryDefaultBranch, githubPreview.data.repository.defaultBranch);
  const githubRepeat = await call('/api/project-import/github', { repositoryUrl: githubUrl, name: 'Public GitHub acceptance' });
  assert.equal(githubRepeat.data.project.id, githubImport.data.project.id);
  const githubProject = (await call('/api/project-groups')).data.projects.find((p) => p.id === githubImport.data.project.id);
  assert.equal(githubProject.deployments.length, 0); assert.equal(githubProject.sources.length, 0);
  const inventory = (await call('/api/deployment-inventory')).data;
  assert.equal(inventory.discoveryError, null, JSON.stringify(inventory.discoveryError));
  assert.ok(!inventory.candidates.some((item) => item.name === 'groundcontrol-web'));
  assert.equal(inventory.candidates.filter((item) => item.id === identity).length, 1);
  assert.equal(inventory.candidates.find((item) => item.id === identity).services.length, 2);
  await call('/api/deployment-inventory', { action: 'dismiss', candidateId: identity, hostId: inventory.hostId });
  assert.ok(!(await call('/api/deployment-inventory')).data.candidates.some((item) => item.id === identity));
  const sourcePath = root + '/web app';
  const add = await call('/api/deployment-inventory', { action: 'add_source', sourcePath, hostId: inventory.hostId, name: process.env.GC_TEST_PROJECT_NAME });
  assert.equal(add.status, 201, JSON.stringify(add.data));
  const projectId = add.data.project.id;
  const again = await call('/api/deployment-inventory', { action: 'add_source', sourcePath: sourcePath + '/' });
  assert.equal(again.data.source.id, add.data.source.id);
  const groups = (await call('/api/project-groups')).data.projects;
  assert.equal(groups.find((item) => item.id === projectId).deployments.length, 0);
  assert.equal(groups.find((item) => item.id === projectId).sources[0].path, sourcePath);
  assert.equal((await call('/api/deployment-inventory', { action: 'add_source', sourcePath, hostId: -999 })).status, 409);
  await call('/api/deployment-inventory', { action: 'restore', candidateId: identity });
  const tracked = await call('/api/deployment-inventory', { action: 'enroll', candidateId: identity, projectId, environmentName: 'Production', hostId: inventory.hostId });
  assert.equal(tracked.status, 201, JSON.stringify(tracked.data));
  const stage = await call('/api/deployment-inventory', { action: 'enroll', candidateId: identity + '-stage', projectId, environmentName: 'Staging', hostId: inventory.hostId });
  assert.equal(stage.status, 201, JSON.stringify(stage.data));
  assert.notEqual(tracked.data.deployment.id, stage.data.deployment.id);
  const trackedInventory = (await call('/api/deployment-inventory')).data;
  assert.equal(trackedInventory.deployments.find((item) => item.id === tracked.data.deployment.id).runtime.containers.length, 2);
  assert.equal(trackedInventory.deployments.find((item) => item.id === stage.data.deployment.id).runtime.containers.length, 1);
  assert.ok(!trackedInventory.candidates.some((item) => item.id === identity));
  assert.equal((await call('/api/projects/' + stage.data.deployment.id + '/group', { projectGroupId: projectId, environmentName: 'Preview' }, 'PATCH')).status, 200);
  const invalidLaunch = await call('/api/deployment-inventory', { action: 'launch_local', projectId, name: 'Bad port', environmentName: 'Local', image: process.env.GC_TEST_HTTP_IMAGE, containerPort: -1, hostId: inventory.hostId });
  assert.equal(invalidLaunch.status, 400);
  const launch = await call('/api/deployment-inventory', { action: 'launch_local', projectId, name: 'Local HTTP acceptance', environmentName: 'Local', image: process.env.GC_TEST_HTTP_IMAGE, containerPort: 8080, hostId: inventory.hostId });
  assert.equal(launch.status, 201, JSON.stringify(launch.data));
  assert.equal(launch.data.deployment.projectGroupId, projectId);
  const local = (await call('/api/deployment-inventory/' + launch.data.deployment.slug)).data.deployment;
  assert.equal(local.observedStatus, 'present'); assert.equal(local.runtime.containers.length, 1);
  assert.ok(local.publicUrl.startsWith('http://127.0.0.1:'));
  await call('/api/deployment-inventory', { action: 'unenroll', deploymentId: tracked.data.deployment.id, hostId: inventory.hostId });
  assert.ok(!(await call('/api/deployment-inventory')).data.deployments.some((item) => item.id === tracked.data.deployment.id), 'No silent re-enrolment');
  console.log(JSON.stringify({ folderBrowser: 'passed', macHomeWithUnavailableEntry: 'passed', githubPublicImport: 'passed', githubImportCreatesNoDeployment: 'passed', githubImportIdempotent: 'passed', outsideWorkspaceFolderRead: 'passed', nonComposeDiscovery: 'passed', groupedCompose: 'passed', dismissAndRefresh: 'passed', duplicateSourceAdd: 'idempotent', sourceCreatesNoDeployment: 'passed', selectedHostGuard: 'passed', sharedSourceEnvironments: 'independent', projectAssignment: 'passed', localLaunch: 'passed', localUrl: local.publicUrl, localContainer: launch.data.deployment.containerName, noSilentReenrollment: 'passed' }));
}
main().catch((error) => { console.error(error.stack); process.exitCode = 1; });
